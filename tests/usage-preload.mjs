import assert from 'node:assert/strict';
import {createUsagePreloader} from '../src/usage-preload.js';
let timer, resolve, calls = [], enabled=false;
const loader = createUsagePreloader({enabled:()=>enabled,schedule:fn=>(timer=fn,1),cancel:()=>{timer=null},
  update:ids=>{calls.push(ids);return new Promise(done=>{resolve=done});}});
loader.resume();
assert.equal(timer,undefined,'startup alone cannot schedule any source scan');
loader.changed(['child']);
assert.equal(timer,undefined,'changes without a visible consumer remain dirty');
enabled=true;loader.resume();
loader.pause();
assert.equal(timer,null,'pausing cancels scheduled work without consuming its IDs');
loader.resume();
let pending=timer();timer=null;
assert.deepEqual(calls[0],['child'],'only changed sources are read for a real consumer');
loader.changed(['other','other']);
assert.equal(calls.length,1,'updates serialize');
resolve();await pending;
pending=timer();timer=null;
assert.deepEqual(calls[1],['other']);
loader.invalidate();enabled=false;
resolve();await pending;
assert.equal(timer,null,'closing drops unstarted work');
enabled=true;loader.changed(['new-account']);
pending=timer();timer=null;
assert.deepEqual(calls[2],['new-account'],'old consumer dirt does not leak across context changes');
resolve();await pending;
assert.ok(calls.every(ids=>Array.isArray(ids)&&ids.length),'no initial null/full-range work exists');
console.log('usage preload tests passed');
