import assert from 'node:assert/strict';
import {createUsagePreloader} from '../src/usage-preload.js';
let timer, resolve, calls = [];
const loader = createUsagePreloader({enabled:()=>true,schedule:fn=>(timer=fn,1),cancel:()=>{timer=null},
  invoke:(method,args)=>{calls.push([method,args]);return new Promise(done=>{resolve=done});}});
const catalog = revision => [{id:'chat',metricsRevision:revision}];
loader.catalog(catalog('one'));
assert.equal(timer,undefined,'catalog alone must not use a previous account');
loader.quota({account_id:'a',primary:{window_minutes:300,resets_at:50}});
assert.equal(timer,undefined,'5h alone never preloads usage');
loader.quota({account_id:'a',primary:{window_minutes:300,resets_at:50},secondary:{window_minutes:10080,resets_at:100}});
let pending = timer(); timer = null;
assert.deepEqual(calls[0],['update_current_usage',{threadIds:null}]);
loader.catalog(catalog('two'));
assert.equal(calls.length,1,'startup and incremental work must serialize');
resolve(); await pending;
assert.ok(timer,'settlement during preload must not be lost');
pending = timer(); timer = null;
assert.deepEqual(calls[1][1].threadIds,['chat']);
resolve(); await pending;
loader.catalog(catalog('two'));
assert.equal(timer,null,'unchanged activity does not parse logs');
loader.quota({account_id:'a',primary:{window_minutes:300,resets_at:60},secondary:{window_minutes:10080,resets_at:100}});
assert.equal(timer,null,'a 5h reset does not invalidate W preload');
loader.quota({account_id:'b',primary:{window_minutes:10080,resets_at:100}});
pending = timer(); timer = null;
assert.equal(calls[2][1].threadIds,null,'another account gets a fresh current-period check');
loader.quota({});
resolve(); await pending;
loader.catalog(catalog('three'));
assert.equal(timer,null,'unknown account pauses reuse');
loader.quota({account_id:'b',primary:{window_minutes:10080,resets_at:200}});
pending = timer(); timer = null;
assert.equal(calls[3][1].threadIds,null,'new quota cycle reloads its own range');
resolve(); await pending;
loader.changed(['child']);
pending = timer(); timer = null;
assert.deepEqual(calls[4][1].threadIds,['child']);
resolve(); await pending;
console.log('usage preload tests passed');
